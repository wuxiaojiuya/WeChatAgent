test('image metadata checks full PNG structure, CRC and decoded scanline size before accepting generated bytes',()=>{
  assert.deepEqual(Object.fromEntries(Object.entries(imageMetadata(png)).filter(([key])=>['format','width','height','size'].includes(key))),{format:'png',width:2,height:2,size:png.length});
  for(const bytes of [Buffer.from('PNG'),png.subarray(0,-4),Buffer.concat([png,Buffer.from('trailing')]),Buffer.alloc(16*1024*1024+1)])assert.throws(()=>imageMetadata(bytes),/IMAGE_/);
  const changed=Buffer.from(png);changed[45]^=1;assert.throws(()=>imageMetadata(changed),/IMAGE_FORMAT_INVALID/);
});

